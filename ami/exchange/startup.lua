-- /ami/exchange/startup.lua
-- The Great Ami Exchange v1.0 — entry point.
-- Trimmed from /ami/shop/startup.lua. Run: shell.run("/ami/exchange/startup")
--
-- Players walk up to this computer's terminal:
--   [B] Buy coins  — pay AMI through a wallet invoice, get /coins
--   [S] Sell coins — coins are taken with the command block, AMI is sent
--
-- Peripherals (see exchange_api.lua): modem on BACK, optional monitor on TOP,
-- and a command block on any side.
--
-- SECURITY: this computer can run server commands. Players must only be able
-- to right-click it — never break it, place blocks next to the command block,
-- or reach a shell. Ctrl+T is disabled below and admin functions sit behind
-- the hidden backtick (`) key + password; the build itself must be protected
-- (claimed chunk / spawn protection).

package.path = package.path .. ";/ami/exchange/?.lua"

-- Ctrl+T must not drop a player into a shell next to a command block.
os.pullEvent = os.pullEventRaw

local api = require("exchange_api")
local ui  = require("exchange_ui")

local SYNC_INTERVAL = 30   -- seconds between reserve refreshes
local POLL_INTERVAL = 4    -- seconds between payment checks while waiting
local SHOP_CHANNEL  = 1338
local REPO_BASE     = "https://raw.githubusercontent.com/Teru-dot-png/amicoin-fullpower/refs/heads/main"

local UPDATE_FILES = {
    { src = "/shared/xtea.lua",                dst = "/shared/xtea.lua"                },
    { src = "/ami/exchange/exchange_api.lua",  dst = "/ami/exchange/exchange_api.lua"  },
    { src = "/ami/exchange/exchange_ui.lua",   dst = "/ami/exchange/exchange_ui.lua"   },
    { src = "/ami/exchange/startup.lua",       dst = "/ami/exchange/startup.lua"       },
}

-- ── Config helpers ────────────────────────────────────────────────────────────
local function loadCfg()   return api.loadConfig() end
local function saveCfg(c)  api.saveConfig(c) end

-- ── Lock-down ─────────────────────────────────────────────────────────────────
-- A reboot (Ctrl+R) must come straight back here, and a floppy placed next to
-- the computer must not be able to run its own startup.
local function lockDown()
    settings.set("shell.allow_disk_startup", false)
    settings.save()
    if not fs.exists("/startup.lua") then
        local f = fs.open("/startup.lua", "w")
        f.write("-- Auto-generated by /ami/exchange/startup.lua\n")
        f.write('shell.run("/ami/exchange/startup")\n')
        f.close()
    end
end

-- ── FNV-1a hash (for self-update fingerprint verification) ───────────────────
local function fnv1a(s)
    local hash = 2166136261
    for i = 1, #s do
        hash = bit32.bxor(hash, string.byte(s, i))
        hash = (hash * 16777619) % 4294967296
    end
    return string.format("%08x", hash)
end

-- ── Self-update ───────────────────────────────────────────────────────────────
local function selfUpdate()
    term.clear(); term.setCursorPos(1, 1)
    term.setTextColor(colors.yellow)
    print("Ami Exchange Self-Update")
    print("Downloading from GitHub...")
    print("")
    term.setTextColor(colors.white)

    -- Delta-check helper: hash a file on disk, nil if absent.
    local function hashFile(path)
        if not fs.exists(path) then return nil end
        local f = fs.open(path, "r")
        local c = f.readAll(); f.close()
        return fnv1a(c)
    end
    local failed = false
    local hashes = {}

    for _, entry in ipairs(UPDATE_FILES) do
        io.write("  " .. entry.dst .. " ... ")
        local res = http.get(REPO_BASE .. entry.src)
        if not res then
            term.setTextColor(colors.red)
            print("FAILED (no response)")
            term.setTextColor(colors.white)
            failed = true
        else
            local content = res.readAll(); res.close()
            if #content < 64 then
                term.setTextColor(colors.red)
                print("FAILED (too short — 404?)")
                term.setTextColor(colors.white)
                failed = true
            else
                local remoteHash = fnv1a(content)
                if hashFile(entry.dst) == remoteHash then
                    term.setTextColor(colors.gray)
                    print("skip  [" .. remoteHash .. "]")
                    term.setTextColor(colors.white)
                    hashes[#hashes + 1] = remoteHash
                else
                    local bakPath = entry.dst .. ".bak"
                    if fs.exists(entry.dst) then
                        if fs.exists(bakPath) then fs.delete(bakPath) end
                        pcall(fs.copy, entry.dst, bakPath)
                    end
                    local f = fs.open(entry.dst, "w")
                    f.write(content); f.close()
                    if hashFile(entry.dst) ~= remoteHash then
                        if fs.exists(bakPath) then
                            pcall(fs.delete, entry.dst)
                            pcall(fs.copy, bakPath, entry.dst)
                        end
                        term.setTextColor(colors.red)
                        print("FAILED (verify -- backup restored)")
                        term.setTextColor(colors.white)
                        failed = true
                    else
                        term.setTextColor(colors.green)
                        print("OK  [" .. remoteHash .. "]")
                        term.setTextColor(colors.white)
                        hashes[#hashes + 1] = remoteHash
                    end
                end
            end
        end
    end

    print("")
    if failed then
        term.setTextColor(colors.red)
        print("Update failed. Backup files (.bak) retained.")
        print("The exchange will continue running the old version.")
        term.setTextColor(colors.white)
        os.sleep(3)
    else
        local combined = table.concat(hashes, ":")
        term.setTextColor(colors.green)
        print("Update complete!")
        term.setTextColor(colors.yellow)
        print("Fingerprint : " .. fnv1a(combined))
        term.setTextColor(colors.white)
        print("Rebooting in 3 seconds...")
        os.sleep(3)
        os.reboot()
    end
end

-- ── Terminal helpers ──────────────────────────────────────────────────────────
local function header(title)
    term.setBackgroundColor(colors.black)
    term.setCursorPos(1, 1); term.clear()
    term.setTextColor(colors.orange)
    print("  " .. title)
    term.setTextColor(colors.gray)
    print("  ----------------------------------------")
    term.setTextColor(colors.white)
end

local function say(color, text)
    term.setTextColor(color); print(text); term.setTextColor(colors.white)
end

local function ask(prompt)
    io.write(prompt)
    return ((io.read() or ""):gsub("^%s+", ""):gsub("%s+$", ""))
end

-- Menus read "char" events, not "key": a key press is followed by a char
-- event, and reacting to the key would leave that character to be typed into
-- the next prompt. Loops because Ctrl+T ("terminate") ignores the filter.
local function menuKey()
    while true do
        local ev, ch = os.pullEvent("char")
        if ev == "char" then return ch:lower() end
    end
end

local function anyKey()
    term.setTextColor(colors.gray)
    print("")
    print("  Press any key...")
    term.setTextColor(colors.white)
    os.pullEvent("key")
    os.sleep(0.1)   -- swallow the char event that follows the key
end

-- Short form used in the wallet's title bar: a1b2..c3d4
local function shortAddr(addr)
    return addr:sub(1, 4) .. ".." .. addr:sub(-4)
end

local lastStatus = nil   -- last trade line for the monitor

local function drawBoard()
    local cfg = loadCfg()
    local open, reason = api.isOpen()
    ui.draw({
        name    = cfg.shop_name,
        rate    = cfg.rate,
        reserve = api.getShopBal(),
        open    = open,
        reason  = reason,
        status  = lastStatus,
    })
end

-- ── Periodic reserve sync ─────────────────────────────────────────────────────
local function syncLoop()
    api.registerShop()
    api.witnessBalance()
    drawBoard()
    while true do
        os.sleep(SYNC_INTERVAL)
        api.witnessBalance()
        drawBoard()
    end
end

