if not api.hasAdminPass() then
    print("============================================")
    print("  First-Run Setup: Set Admin Password")
    print("============================================")
    print("")
    print("No admin password is set. Create one now.")
    print("(This is used to unlock the admin panel.)")
    print("")
    local pw1, pw2
    repeat
        io.write("New password: ")
        pw1 = read("*")
        if #pw1 < 4 then
            print("Too short -- minimum 4 characters.")
        else
            io.write("Confirm password: ")
            pw2 = read("*")
            if pw1 ~= pw2 then
                print("Passwords do not match, try again.")
                pw1 = nil
            end
        end
    until pw1 and pw1 == pw2
    api.setAdminPass(pw1)
    term.setTextColor(colors.green)
    print("Password saved.")
    term.setTextColor(colors.white)
    print("")
    print("Next: press ` (backtick) on the main screen, add a")
    print("node, then run the safety test to open trading.")
    print("")
end

print("Starting in 3 seconds...")
os.sleep(3)

ui.init(api.getMonitor())
drawBoard()

-- If inputLoop returns (admin chose Quit), the sync loop is killed with it.
-- A crash must not leave a shell open next to the command block: reboot.
local ok, err = pcall(parallel.waitForAny, inputLoop, syncLoop)
if not ok then
    api.log("ERROR", "startup", "crashed: " .. tostring(err))
    term.setTextColor(colors.red)
    print("Ami Exchange crashed -- rebooting in 5 seconds.")
    print(tostring(err))
    os.sleep(5)
    os.reboot()
end
