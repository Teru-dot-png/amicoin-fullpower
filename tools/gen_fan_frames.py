#!/usr/bin/env python3
"""Pre-render the AmiCoin parametric fan into static ASCII frames.

Output: ami/lib/ui/widgets/fan_frames.lua

Each frame is an array of row-strings (exactly COLS chars wide), using Lua
3-digit decimal escapes (\\219 etc.) so CC:Tweaked sees the raw CP437 byte.
Runtime just blits one string per row => 9 writes/frame, zero trig.
"""
import math

ASPECT = 2.0
RADIUS = 4
BLADES = 4
TWIST  = 0.25
FRAMES = 8           # one seamless loop = rotation sweeps 2*pi/BLADES

COLS = int(RADIUS * ASPECT * 2) + 1   # 17
ROWS = RADIUS * 2 + 1                  # 9
CX = (COLS - 1) / 2
CY = (ROWS - 1) / 2

# shade ramp: full, dark, medium, light, air
FULL, DARK, MED, LIGHT, AIR = 219, 178, 177, 176, 32


def shade_at(col, row, rotation):
    dx = (col - CX) / ASPECT
    dy = (row - CY)
    dist = math.sqrt(dx * dx + dy * dy)

    if dist > RADIUS + 0.3:
        return AIR
    if dist < RADIUS * 0.1:
        return FULL  # hub

    angle = math.atan2(dy, dx)
    s = math.sin(BLADES * angle + TWIST * dist + rotation)

    if s > 0.55:
        idx = 0
    elif s > 0.15:
        idx = 1
    elif s > -0.2:
        idx = 2
    else:
        idx = 4  # air

    # soften rim
    if dist > RADIUS * 0.92 and idx < 4:
        idx = min(idx + 1, 4)

    return [FULL, DARK, MED, LIGHT, AIR][idx]


def build_frame(rotation):
    rows = []
    for row in range(ROWS):
        codes = [shade_at(col, row, rotation) for col in range(COLS)]
        rows.append("".join("\\%03d" % c for c in codes))
    return rows


def main():
    frames = []
    for i in range(FRAMES):
        rotation = i * (2 * math.pi / BLADES) / FRAMES
        frames.append(build_frame(rotation))

    out = []
    out.append("-- ami/lib/ui/widgets/fan_frames.lua")
    out.append("-- AUTO-GENERATED by tools/gen_fan_frames.py - do not edit by hand.")
    out.append("-- Pre-rendered parametric fan: %d frames, %dx%d, blades=%d radius=%d."
               % (FRAMES, COLS, ROWS, BLADES, RADIUS))
    out.append("-- Runtime blits one row-string per line (zero trig).")
    out.append("return {")
    out.append("  cols = %d," % COLS)
    out.append("  rows = %d," % ROWS)
    out.append("  frames = {")
    for f in frames:
        out.append("    {")
        for r in f:
            out.append('      "%s",' % r)
        out.append("    },")
    out.append("  },")
    out.append("}")
    text = "\n".join(out) + "\n"

    path = "ami/lib/ui/widgets/fan_frames.lua"
    with open(path, "w") as fh:
        fh.write(text)
    print("Wrote %s (%d frames, %dx%d)" % (path, FRAMES, COLS, ROWS))


if __name__ == "__main__":
    main()
